export function translatePtToZh(pt: string, enFallback: string): string {
  if (ZH_PHRASES[pt]) return ZH_PHRASES[pt];

  // Dynamic patterns with counts / codes / interpolated names
  let m = pt.match(/^Ver todos os (\d+) serviços$/);
  if (m) return `查看全部 ${m[1]} 項服務`;

  m = pt.match(/^Todos os Serviços \((\d+)\)$/);
  if (m) return `全部服務項目 (${m[1]})`;

  m = pt.match(/^Todas as Categorias \((\d+)\)$/);
  if (m) return `全部分類 (${m[1]})`;

  m = pt.match(/^Todas \((\d+)\)$/);
  if (m) return `全部 (${m[1]})`;

  m = pt.match(/^Serviço (.+)$/);
  if (m) return `技術服務 ${m[1]}`;

  m = pt.match(/^Área Técnica (.+)$/);
  if (m) return `專業技術領域 ${m[1]}`;

  m = pt.match(/^Avaliação:\s*(\d+)\s*de\s*5$/);
  if (m) return `評分：${m[1]} / 5 顆星`;

  m = pt.match(/^(\d+)\s*de\s*5$/);
  if (m) return `${m[1]} / 5 顆星`;

  m = pt.match(/^Sem projectos publicados na categoria "(.+)"$/);
  if (m) return `「${m[1]}」分類目前尚無公開專案`;

  return enFallback;
}
